-- CampusConnect final features. Apply once after 001_auth_rbac.sql.
alter table public.profiles
  add column if not exists is_banned boolean not null default false,
  add column if not exists ban_reason text,
  add column if not exists banned_at timestamptz,
  add column if not exists updated_at timestamptz not null default now();

create table if not exists public.groups (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 2 and 100),
  description text not null default '',
  owner_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists groups_owner_id_idx on public.groups(owner_id);

create table if not exists public.group_members (
  id uuid primary key default gen_random_uuid(),
  group_id uuid not null references public.groups(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  can_create_requests boolean not null default false,
  can_edit_requests boolean not null default false,
  can_assign_requests boolean not null default false,
  created_at timestamptz not null default now(),
  unique (group_id, user_id)
);
create index if not exists group_members_user_id_idx on public.group_members(user_id);

alter table public.service_requests
  add column if not exists group_id uuid references public.groups(id) on delete set null,
  add column if not exists assigned_to uuid references public.profiles(id) on delete set null;
create index if not exists service_requests_group_id_idx on public.service_requests(group_id);
create index if not exists service_requests_assigned_to_idx on public.service_requests(assigned_to);

-- Refresh tokens are stored only as hashes. Access-token hashes allow immediate session revocation.
create table if not exists public.app_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  refresh_token_hash text not null unique,
  access_token_hash text unique,
  device_name text not null default 'Browser',
  ip_address text,
  user_agent text,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  expires_at timestamptz not null,
  revoked_at timestamptz
);
alter table public.app_sessions add column if not exists access_token_hash text unique;
create index if not exists app_sessions_user_id_idx on public.app_sessions(user_id);
create index if not exists app_sessions_active_idx on public.app_sessions(user_id, revoked_at, expires_at);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null,
  entity_type text not null default 'system',
  entity_id text,
  ip_address text,
  user_agent text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists activity_logs_actor_idx on public.activity_logs(actor_id, created_at desc);
create index if not exists activity_logs_created_idx on public.activity_logs(created_at desc);

create table if not exists public.security_events (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  event_type text not null,
  email text,
  ip_address text,
  user_agent text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists security_events_created_idx on public.security_events(created_at desc);
create index if not exists security_events_ip_idx on public.security_events(ip_address, created_at desc);
create index if not exists security_events_email_idx on public.security_events(email, created_at desc);

create table if not exists public.login_attempts (
  id bigint generated by default as identity primary key,
  email text not null,
  ip_address text not null,
  succeeded boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists login_attempts_lookup_idx
  on public.login_attempts(email, ip_address, succeeded, created_at desc);

-- Backend service-role access only; browser users receive no direct policies.
alter table public.groups enable row level security;
alter table public.group_members enable row level security;
alter table public.app_sessions enable row level security;
alter table public.activity_logs enable row level security;
alter table public.security_events enable row level security;
alter table public.login_attempts enable row level security;
